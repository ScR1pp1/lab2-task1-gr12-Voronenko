#include <stdio.h>
#include <stdlib.h>
#include <math.h>

/* Прототипы функций */
int isPerfectSquare(int number);
void printPerfectSquares(int arr[], int size);

/*
 * Функция: isPerfectSquare
 * Описание: Проверяет, является ли число полным квадратом
 * Параметры: number - целое число для проверки
 * Возвращает: 1 если число полный квадрат, 0 в противном случае
 */
int isPerfectSquare(int number) {
		if (number < 0) return 0;  /* Отрицательные числа не могут быть полными квадратами */

		int root = (int)sqrt(number);  /* Вычисляем целую часть квадратного корня */
		return (root * root == number) ? 1 : 0;  /* Проверяем, дает ли корень исходное число */
}

/*
 * Функция: printPerfectSquares
 * Описание: Выводит все полные квадраты из массива
 * Параметры: arr - массив целых чисел, size - размер массива
 * Возвращает: void
 */
void printPerfectSquares(int arr[], int size) {
		printf("Полные квадраты в массиве:\n");
		int found = 0;  /* Флаг для отслеживания найденных квадратов */

		for (int i = 0; i < size; i++) {
				if (isPerfectSquare(arr[i])) {
						printf("%d (квадрат числа %d)\n", arr[i], (int)sqrt(arr[i]));
						found = 1;
				}
		}

		if (!found) {
				printf("Полные квадраты не найдены.\n");
		}
}

/*
 * Функция: main
 * Описание: Точка входа в программу. Обрабатывает аргументы командной строки.
 * Параметры: argc - количество аргументов, argv - массив значений аргументов
 * Возвращает: 0 при успешном выполнении, 1 при ошибке
 */
int main(int argc, char *argv[]) {	
		/* Проверяем, достаточно ли аргументов */
		if (argc < 2) {
				printf("Использование: %s <размер> <числа...>\n", argv[0]);
				printf("Пример: %s 5 1 4 9 16 25\n", argv[0]);
				return 1;
		}

		/* Преобразуем размер массива из строки в число */
		int size = atoi(argv[1]);
		if (size <= 0) {
				printf("Ошибка: Размер массива должен быть положительным\n");
				return 1;
		}

		/* Проверяем, соответствует ли количество введенных чисел указанному размеру */
		if (argc - 2 < size) {
				printf("Ошибка: Ожидалось %d чисел, но получено %d\n", size, argc - 2);
				return 1;
		}

		/* Выделяем память под массив */
		int *numbers = (int*)malloc(size * sizeof(int));
		if (numbers == NULL) {
				printf("Ошибка: Не удалось выделить память\n");
				return 1;
		}

		/* Заполняем массив числами из аргументов командной строки */
		printf("Исходный массив:\n");
		for (int i = 0; i < size; i++) {
				numbers[i] = atoi(argv[i + 2]);
				if (numbers[i] <= 0) {
						printf("Ошибка: Число %d не является натуральным\n", numbers[i]);
						free(numbers);  /* Освобождаем память перед выходом */
						return 1;
				}
				printf("%d ", numbers[i]);
		}
		printf("\n\n");

		/* Находим и выводим полные квадраты */
		printPerfectSquares(numbers, size);

		/* Освобождаем выделенную память */
		free(numbers);
		return 0;
}